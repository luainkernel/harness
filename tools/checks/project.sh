# Sourced by the shared scripts: what they read of the project that mounts the harness, since the same
# file runs in each project that mounts it. The checkout answers what it carries, its origin, its
# default branch and where the mount sits; the project answers the rest in its .agents/harness.conf, a
# line <key>=<value> for each, an extended regex over the paths of its tree, or names, of checks of its own
# under its tools/checks/ or of repositories, a # opening a comment:
#   code       what a commit of the session's own thread carries as code (implement-guard.sh)
#   api        what a script writes or calls, which a pull request body shows (pr-body.sh)
#   tools      under the harness's own directories, what is the project's code and not the harness
#              (harness-mixed.sh, functional.sh)
#   unread     what the host cycle reads nothing of, past the harness and the documents (functional.sh)
#   generated  what the comment, style and shape checks and luals.sh do not read, generated by the build
#   vendored   what lua-style.sh, function-shape.sh and luals.sh do not read either, code another
#              project wrote
#   host       the Lua that runs once on the host, where lua-style.sh names an alias of a module's field
#   edit       the file checks of its own on-edit.sh runs over an edited file
#   advisory   the file checks of its own advisory.sh runs over a change
#   commit     the commit checks of its own advisory.sh runs over each commit
#   range      the rev-range checks of its own review-packet.sh runs over a change
#   repos      the other repositories that mount the harness, owner/name, whose pull requests and issues
#              the post guards read as the checkout's (gh_family in commands.sh)
#   budget     the ceiling in bytes of the project's AGENTS.md (context-budget.sh)
#   replaces   the conventions of CONVENTIONS.md the project keeps its own in place of, by the check that
#              holds each: title (title.sh), decision (decision.sh), merge (merge-guard.sh), and license
#              and blank (the header and the trailing blank line pre-commit reads), or by the step the
#              workflows take for it, which a launch passes this value for: smallest (a mechanism past
#              the small shape kept only with a source), complexity (the label) and mechanism (a change
#              split into two pull requests)
# A key the project leaves out gives nothing: no path, no check, no repository.

# the checkout of the harness this file is in, through any link to it
harness_root() {
	(cd "$(dirname "$(readlink -f "${BASH_SOURCE[0]}")")/../.." && pwd)
}

# the checkout of the project that mounts the harness, or the harness itself where nothing mounts it
project_root() {
	local harness project
	harness=$(harness_root)
	project=$(git -C "$harness" rev-parse --show-superproject-working-tree 2> /dev/null)
	printf '%s\n' "${project:-$harness}"
}

# the common git directory of the checkout <dir> is in, its superproject's where <dir> is inside a mount,
# whose own sits under the superproject's .git/modules
project_common() {
	local super
	super=$(git -C "${1:-.}" rev-parse --show-superproject-working-tree 2> /dev/null)
	git -C "${super:-${1:-.}}" rev-parse --path-format=absolute --git-common-dir 2> /dev/null
}

# the path of the mount under the project's root; nothing where nothing mounts the harness
project_mount() {
	local harness project
	harness=$(harness_root)
	project=$(project_root)
	[ "$harness" = "$project" ] || printf '%s\n' "${harness#"$project"/}"
}

# the value of <key> in the .agents/harness.conf of the checkout <dir> belongs to, or of the project's
# where that checkout carries none, as a tree older than the mount does
project_conf() {
	local top conf
	top=$(git -C "${2:-.}" rev-parse --show-toplevel 2> /dev/null)
	conf=$top/.agents/harness.conf
	[ -n "$top" ] && [ -f "$conf" ] || conf=$(project_root)/.agents/harness.conf
	sed -n "s/^$1=//p" "$conf" 2> /dev/null | tail -n 1
}

# whether the project of the checkout <dir> keeps the convention <name> of CONVENTIONS.md, which it does
# unless its replaces key names it
project_keeps() {
	! project_conf replaces "$2" | tr ' ' '\n' | grep -qxF "$1"
}

# the repository on GitHub the checkout <dir> pushes to, owner/name from its origin, as gh takes the
# repository of a command that names none; nothing where it has no origin
project_repo() {
	git -C "${1:-.}" remote get-url origin 2> /dev/null | sed -E 's#\.git$##; s#/+$##; s#^.*[:/]([^/:]+/[^/:]+)$#\1#'
}

# the branch the repository of the checkout <dir> merges into: the one origin's HEAD names, else master
# or main as origin carries it, else master
project_trunk() {
	local ref
	ref=$(git -C "${1:-.}" symbolic-ref -q --short refs/remotes/origin/HEAD 2> /dev/null) && { printf '%s\n' "${ref#origin/}"; return; }
	for ref in master main; do
		git -C "${1:-.}" rev-parse -q --verify "refs/remotes/origin/$ref" > /dev/null 2>&1 && { printf '%s\n' "$ref"; return; }
	done
	echo master
}

